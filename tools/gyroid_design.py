# The gyroid pixel art of "Gyroid's menu", placed by hand after a picture of an Animal Crossing:
# City Folk gyroid (knob, rounded dome, brim, oval eyes, "o" mouth, one arm down and one up, base
# ring) plus a little cuteness: sparkles in the eyes and blush. Writes source/program/gyroid_sprite.inc
# (read by slumber_app.cpp and phone_icon.py) and optionally a zoomed PNG preview.
#
# usage: python tools/gyroid_design.py source/program/gyroid_sprite.inc [preview.png]
import sys
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
import gyroid_art
from PIL import Image
C = {'h': (236, 152, 88), 'L': (252, 196, 134), 'd': (200, 112, 60), 'O': gyroid_art.OUTLINE,
     'E': (44, 24, 16), 'W': (255, 250, 240), 'p': (246, 128, 118)}
W, H = 24, 25
def build(pose):
    g = [[None] * W for _ in range(H)]
    def put(x, y, k): g[y + 1][x] = C[k]
    def span(y, x0, x1, k, light=0, shade=0):
        for x in range(x0, x1 + 1):
            put(x, y, 'L' if x < x0 + light else 'd' if x > x1 - shade else k)
    # knob, dome, brim
    span(0, 11, 12, 'h', 1)
    span(1, 10, 13, 'h', 1, 1)
    span(2, 8, 15, 'h', 2, 2)
    span(3, 6, 17, 'h', 3, 2)
    span(4, 5, 18, 'h', 3, 3)
    span(5, 4, 19, 'h', 3, 3)
    span(6, 3, 20, 'h', 4, 3)
    span(7, 3, 20, 'O')
    # body
    for y in range(8, 20): span(y, 6, 17, 'h', 1, 1)
    # base ring
    span(20, 5, 18, 'O')
    span(21, 5, 18, 'h', 2, 2)
    span(22, 5, 18, 'd')
    # arms: pose 0 = left out then down, right out then up (as in the picture); pose 1 swaps them,
    # so alternating the two frames flaps the arms like a gyroid playing its sound
    for y in (12, 13): span(y, 2, 5, 'h'); span(y, 18, 21, 'h')
    for y in ((14, 15, 16) if pose == 0 else (10, 11)): span(y, 2, 3, 'h', 1)
    for y in ((10, 11) if pose == 0 else (14, 15, 16)): span(y, 20, 21, 'h', 0, 1)
    # face: oval eyes with a sparkle, blush, little "o" mouth
    for y in (10, 11, 12, 13):
        for x in (8, 9, 14, 15): put(x, y, 'E')
    put(8, 10, 'W'); put(14, 10, 'W')
    for x in (7, 8, 15, 16): put(x, 15, 'p')
    for y in (16, 17):
        for x in (11, 12): put(x, y, 'E')
    # auto outline
    for y in range(H):
        for x in range(W):
            if g[y][x] is None and any(0 <= y + dy < H and 0 <= x + dx < W and g[y + dy][x + dx] not in (None, C['O'])
                                       for dy, dx in ((-1, 0), (1, 0), (0, -1), (0, 1))):
                g[y][x] = C['O']

    return g

frames = [build(0), build(1)]
gyroid_art.write_inc(frames, sys.argv[1], 'gyroid_cf.png')
text = open(sys.argv[1]).read().replace('Generated by tools/gyroid_art.py from gyroid_cf.png - regenerate rather than edit.',
    'Generated by tools/gyroid_design.py (hand-placed after a City Folk gyroid) - edit that, not this.')
open(sys.argv[1], 'w').write(text)
if len(sys.argv) < 3: sys.exit(0)
g = frames[0] + [[None] * W] + frames[1]   # preview: both poses, one above the other
img = Image.new('RGBA', (W, len(g)))
for y in range(len(g)):
    for x in range(W):
        if g[y][x]: img.putpixel((x, y), g[y][x] + (255,))
bg = Image.new('RGBA', (W * 12 + 40, len(g) * 12 + 40), (124, 204, 118, 255))
bg.alpha_composite(img.resize((W * 12, len(g) * 12), Image.NEAREST), (20, 20))
bg.save(sys.argv[2])
