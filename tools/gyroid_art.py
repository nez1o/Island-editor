# Turns a picture of a gyroid into the pixel art used by "Gyroid's menu": the menu's header watermark
# (slumber_app.cpp) and the phone app icon (phone_icon.py) both read source/program/gyroid_sprite.inc.
#
# usage: python tools/gyroid_art.py <picture.png> source/program/gyroid_sprite.inc [height] [colours]
#   height: sprite height in pixels (default 20), colours: palette size before the outline (default 7)
#   needs Pillow (pip install pillow)
#
# Steps: crop to the picture's opaque part, shrink to <height> pixels tall (box filter), keep pixels that
# are at least half opaque, reduce them to a few flat colours, then add a 1-pixel dark outline around the
# silhouette, the way hand-made pixel art usually looks.
import sys, os, re
from PIL import Image

OUTLINE = (72, 46, 28)


def to_pixel_art(img, height=20, colours=7):
    img = img.convert('RGBA')
    bbox = img.getchannel('A').point(lambda a: 255 if a >= 32 else 0).getbbox()
    if bbox: img = img.crop(bbox)
    inner_h = height - 2                       # room for the outline
    inner_w = max(1, round(img.width * inner_h / img.height))
    small = img.resize((inner_w, inner_h), Image.BOX)
    opaque = Image.new('RGB', small.size, (0, 0, 0))
    mask = small.getchannel('A').point(lambda a: 255 if a >= 128 else 0)
    opaque.paste(small.convert('RGB'), (0, 0), mask)
    q = opaque.quantize(colors=colours + 1, method=Image.Quantize.MEDIANCUT)   # +1: the black fill
    pal = q.getpalette()[:3 * (colours + 1)]
    w, h = inner_w + 2, inner_h + 2
    grid = [[None] * w for _ in range(h)]
    for y in range(inner_h):
        for x in range(inner_w):
            if mask.getpixel((x, y)):
                i = q.getpixel((x, y))
                grid[y + 1][x + 1] = tuple(pal[3 * i:3 * i + 3])
    for y in range(h):                         # outline: empty pixels touching the silhouette
        for x in range(w):
            if grid[y][x] is not None: continue
            if any(0 <= y + dy < h and 0 <= x + dx < w and grid[y + dy][x + dx] not in (None, OUTLINE)
                   for dy, dx in ((-1, 0), (1, 0), (0, -1), (0, 1))):
                grid[y][x] = OUTLINE
    return grid


def write_inc(frames, path, source):
    """frames: one grid, or a list of same-size grids (animation frames sharing one palette)."""
    if frames and frames[0] and not isinstance(frames[0][0], list): frames = [frames]
    colours = []
    for grid in frames:
        for row in grid:
            for c in row:
                if c is not None and c not in colours: colours.append(c)
    assert len(colours) <= 15
    keys = '123456789abcdef'
    h, w = len(frames[0]), len(frames[0][0])
    out = ['/* Gyroid pixel art for "Gyroid\'s menu" (header watermark + phone icon, which uses frame 0).',
           '   Generated by tools/gyroid_art.py from %s - regenerate rather than edit.' % source,
           '   One char per pixel: "." transparent, 1-f = k_GyroidPalette[n - 1]. */',
           'static const uint8_t k_GyroidPalette[][3] = {']
    out += ['    { %d, %d, %d },' % c for c in colours]
    out += ['};', 'static const char* const k_Gyroid[][%d] = {' % h]
    for grid in frames:
        out.append('    {')
        out += ['        "%s",' % ''.join('.' if c is None else keys[colours.index(c)] for c in row) for row in grid]
        out.append('    },')
    out += ['};', 'constexpr int GyroidFrames = %d, GyroidW = %d, GyroidH = %d;' % (len(frames), w, h), '']
    open(path, 'w').write('\n'.join(out))


def read_inc(path):
    """-> (rows of frame 0, palette) for phone_icon.py."""
    text = open(path).read()
    pal = [tuple(int(v) for v in m) for m in re.findall(r'\{ (\d+), (\d+), (\d+) \}', text)]
    h = int(re.search(r'GyroidH = (\d+)', text).group(1))
    rows = re.findall(r'^        "([.0-9a-f]+)",$', text, re.M)[:h]
    return rows, pal


if __name__ == '__main__':
    src, dst = sys.argv[1:3]
    height = int(sys.argv[3]) if len(sys.argv) > 3 else 20
    colours = int(sys.argv[4]) if len(sys.argv) > 4 else 7
    grid = to_pixel_art(Image.open(src), height, colours)
    write_inc(grid, dst, os.path.basename(src))
    for row in read_inc(dst)[0]: print(row)
