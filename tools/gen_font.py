# Generates source/program/app_font.inc: the bitmap glyphs (ASCII 32-126) the Slumber app screen
# draws its text with, at 720p (scale 1) and 1080p (scale 1.5) sizes.
#
# Font: Inter (https://rsms.me/inter, SIL Open Font License 1.1).
#
# usage: python tools/gen_font.py <dir with Inter-*.otf> source/program/app_font.inc
#   needs Pillow (pip install pillow)
import sys, os
from PIL import Image, ImageDraw, ImageFont

FONT_DIR, OUT = sys.argv[1:3]
# name, file, pixel size at 720p
FONTS = [
    ('Title', 'Inter-Bold.otf', 26),
    ('Body', 'Inter-SemiBold.otf', 19),
    ('Small', 'Inter-Medium.otf', 15),
]
SCALES = [('1', 1.0), ('2', 1.5)]
CHARS = [chr(c) for c in range(32, 127)]

out = ['/* Generated by tools/gen_font.py from Inter (SIL Open Font License 1.1) - do not edit.',
       '   Glyph pixels: one hex digit (coverage 0-15) per pixel, row by row. */', '']
total = 0
for name, fname, size in FONTS:
    for suffix, scale in SCALES:
        px = round(size * scale)
        font = ImageFont.truetype(os.path.join(FONT_DIR, fname), px)
        ascent, descent = font.getmetrics()
        glyphs, pixels = [], []
        for ch in CHARS:
            adv = font.getlength(ch)
            x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
            w, h = max(0, x1 - x0), max(0, y1 - y0)
            off = len(pixels)
            if w and h:
                img = Image.new('L', (w, h), 0)
                ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
                for v in img.getdata():
                    pixels.append('0123456789abcdef'[(v * 15 + 127) // 255])
            glyphs.append('{%d, %d, %d, %d, %d, %d}' % (w, h, x0, y0, round(adv * 8), off))
        ident = '%s_%s' % (name, suffix)
        out.append('static const AppGlyph k_Glyphs_%s[%d] = {' % (ident, len(CHARS)))
        for i in range(0, len(glyphs), 6):
            out.append('    ' + ', '.join(glyphs[i:i + 6]) + ',')
        out.append('};')
        data = ''.join(pixels)
        out.append('static const char k_Pixels_%s[] =' % ident)
        for i in range(0, len(data), 120):
            out.append('    "%s"' % data[i:i + 120])
        out.append(';')
        out.append('static const AppFont k_Font_%s = { %d, %d, k_Glyphs_%s, k_Pixels_%s };' % (ident, ascent, descent, ident, ident))
        out.append('')
        total += len(data)
open(OUT, 'w').write('\n'.join(out))
print('wrote', OUT, total, 'pixels')
